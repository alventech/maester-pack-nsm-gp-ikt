"""Build the pack for Maester 2.x, where packs do not exist, as custom tests.

Usage: python3 tools/build_maester2.py [--out dist]

Writes <out>/NSM/ and <out>/nsm-gp-ikt-maester2-<version>.zip. Users unpack the zip into tests/Custom/ of their
Maester 2 tests folder, where Update-MaesterTests leaves it alone. The folder holds:
- tests/ and helpers/: the pack's tests, documentation and helpers, with the [MaesterTest()] attribute removed,
  since Maester 2 cannot invoke a function that carries an attribute it does not know;
- MP.NSM.<n>.Tests.ps1: one Pester file per test, with the attribute's title, tags, severity and licences;
- NsmMaester2.ps1 (from maester2/): Get-MtSetting, the licence check and the test documentation;
- README.md (from maester2/).

The output is built on each release and not kept in the repository.
"""
import argparse
import json
import re
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).parent.parent
PACK = ROOT / "nsm-gp-ikt"
SRC = ROOT / "maester2"


def attribute_span(text):
    """Start and end of the [MaesterTest(...)] attribute, honouring parentheses inside quoted strings."""
    start = text.index("[MaesterTest(")
    depth, i, quoted = 0, start, False
    while i < len(text):
        c = text[i]
        if quoted:
            if c == "'" and text[i + 1:i + 2] == "'":
                i += 1
            elif c == "'":
                quoted = False
        elif c == "'":
            quoted = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                end = text.index("]", i) + 1
                # Take the line break and the indentation of the next line with it.
                while end < len(text) and text[end] in " \t":
                    end += 1
                if text[end:end + 1] == "\n":
                    end += 1
                line_start = text.rfind("\n", 0, start) + 1
                return line_start, end
        i += 1
    raise ValueError("unterminated MaesterTest attribute")


def values(block, key):
    """A key of the attribute as a list: 'a' gives ['a'], ('a', 'b') gives ['a', 'b']."""
    m = re.search(rf"^\s*{key}\s*=\s*(\((?:'(?:[^']|'')*'|[^)'])*\)|'(?:[^']|'')*')", block, re.M)
    return [v.replace("''", "'") for v in re.findall(r"'((?:[^']|'')*)'", m.group(1))] if m else []


def ps(s):
    """A PowerShell single-quoted string."""
    return "'" + s.replace("'", "''") + "'"


def wrapper(source, function, meta, version):
    tags = ", ".join(ps(t) for t in meta["Tag"])
    it_tags = ", ".join(ps(t) for t in [meta["Id"], f"Severity:{meta['Severity']}"])
    license_arg = f" -License {', '.join(ps(x) for x in meta['License'])}" if meta["License"] else ""
    md = source.with_suffix(".md").name
    return f"""# Generated by tools/build_maester2.py from nsm-gp-ikt/tests/{source.name} (pack {version}). Do not edit.
BeforeAll {{
    $nsmRoot = $PSScriptRoot
    . (Join-Path $nsmRoot 'NsmMaester2.ps1')
    . (Join-Path $nsmRoot 'helpers/NsmHelpers.ps1')
    . (Join-Path $nsmRoot 'tests/{source.name}')
}}

Describe 'NSM GP-IKT 2.1' -Tag {tags} {{
    It {ps(meta['Id'] + ': ' + meta['Title'])} -Tag {it_tags} {{
        $result = Invoke-MtNsmTest -Name {ps(function)} -Markdown (Join-Path $nsmRoot 'tests/{md}'){license_arg} -Severity {ps(meta['Severity'])}
        if ($null -ne $result) {{ $result | Should -Be $true -Because 'bare høy grad består' }}
    }}
}}
"""


def build(out):
    manifest = json.loads((PACK / "maester-pack.json").read_text(encoding="utf-8"))
    version = manifest["Version"]
    target = out / "NSM"
    if target.exists():
        shutil.rmtree(target)
    (target / "tests").mkdir(parents=True)
    shutil.copytree(PACK / "helpers", target / "helpers")
    shutil.copy(SRC / "NsmMaester2.ps1", target)
    shutil.copy(SRC / "README.md", target)
    shutil.copy(ROOT / "LICENSE", target)

    count = 0
    for source in sorted((PACK / "tests").glob("Test.*.ps1")):
        text = source.read_text(encoding="utf-8")
        start, end = attribute_span(text)
        block = text[start:end]
        meta = {k: values(block, k) for k in ("Id", "Title", "Severity", "License", "Tag")}
        for k in ("Id", "Title", "Severity"):
            if len(meta[k]) != 1:
                raise ValueError(f"{source.name}: {k} must be one string")
            meta[k] = meta[k][0]
        function = re.search(r"^function\s+(\S+)\s*\{", text, re.M | re.I).group(1)
        (target / "tests" / source.name).write_text(text[:start] + text[end:], encoding="utf-8")
        shutil.copy(source.with_suffix(".md"), target / "tests")
        (target / f"{meta['Id']}.Tests.ps1").write_text(wrapper(source, function, meta, version), encoding="utf-8")
        count += 1

    archive = out / f"nsm-gp-ikt-maester2-{version}.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(target.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(out).as_posix())
    print(f"{count} tests -> {target.relative_to(ROOT) if target.is_relative_to(ROOT) else target}, {archive.name}")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=Path, default=ROOT / "dist")
    build(p.parse_args().out.resolve())
