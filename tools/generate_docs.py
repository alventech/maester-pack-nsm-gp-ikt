"""Write the test reference from the tests themselves, so the documentation cannot drift from the code.

Usage: python3 tools/generate_docs.py

Reads every nsm-gp-ikt/tests/Test.*.ps1 (its MaesterTest attribute) and Test.*.md (the levels), and the mapping
catalogue tools/data/mapping.json (clause, strength and scope of each link to NSM), and writes:
- docs/tests.md: one section per test, with its NSM measures, scope, levels, licence and permissions;
- docs/coverage.md: every NSM measure, with the tests that name it, the clause and the strength of the link;
- the table between <!-- mapping:start --> and <!-- mapping:end --> in docs/mapping.md;
- the table between <!-- tests:start --> and <!-- tests:end --> in nsm-gp-ikt/README.md.

Fails when a test's Control does not equal the catalogue's direkte and delvis references, in order.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent
TESTS = ROOT / "nsm-gp-ikt" / "tests"
README = ROOT / "nsm-gp-ikt" / "README.md"
OUT = ROOT / "docs" / "tests.md"
MAPPING = ROOT / "tools" / "data" / "mapping.json"
MAPDOC = ROOT / "docs" / "mapping.md"
START, END = "<!-- tests:start -->", "<!-- tests:end -->"
MSTART, MEND = "<!-- mapping:start -->", "<!-- mapping:end -->"
STRENGTH = {"direkte": "direct", "delvis": "partial", "indikator": "indicator"}
DOMAIN = {"NSM-Identitet": "Identity", "NSM-M365": "Microsoft 365", "NSM-Endepunkt": "Endpoint",
          "NSM-On-prem": "On-premises", "NSM-Leverandører": "Suppliers", "NSM-Virksomhet": "Organisation"}


def attribute(text, key):
    """The value of one key in the MaesterTest attribute: a string, or a list for ('a', 'b')."""
    m = re.search(rf"^\s*{key}\s*=\s*(\(.*?\)|'[^']*')", text, re.M | re.S)
    return re.findall(r"'([^']*)'", m.group(1)) if m else []


def levels(md):
    """The '- **Høy grad:** ...' lines of a test's documentation."""
    return re.findall(r"^- \*\*((?:Høy|Moderat|Liten) grad):\*\* (.+)$", md, re.M)


def write_coverage(frameworks, cites):
    """docs/coverage.md: every NSM measure, the tests that name it, and how strong each link is.

    cites: {control: [(test number, clause, strength, scope)]}. Indicators are listed but never count as coverage.
    """
    gp, alert = frameworks["nsm-gp-ikt"], frameworks["nsm-varsel-2026"]
    counted = {c for c, links in cites.items() if any(s != "indikator" for _, _, s, _ in links)}
    direct = {c for c, links in cites.items() if any(s == "direkte" for _, _, s, _ in links)}
    measured = [r for r in gp.values() if f"nsm-gp-ikt:{r['Id']}" in counted]
    in_alert = [r for r in gp.values() if r["InAlert"]]

    def cell(control):
        return "<br>".join(f"{t}{' ' + cl + ')' if cl else ''}: {STRENGTH[s]}, {sc}" for t, cl, s, sc in cites.get(control, [])) or "–"

    lines = [
        "# Coverage",
        "",
        "Generated by `tools/generate_docs.py` from the tests, the mapping catalogue and the framework files. Do not edit by hand.",
        "",
        f"- GP-IKT 2.1: {len(measured)} of {len(gp)} measures have a test, "
        f"{sum(1 for r in measured if 'nsm-gp-ikt:' + r['Id'] in direct)} of them with at least one direct link.",
        f"- NSM's alert of 27.10.2026: {sum(1 for r in in_alert if r in measured)} of the {len(in_alert)} GP-IKT "
        f"measures it lists have a test, and {sum(1 for i in alert if f'nsm-varsel-2026:{i}' in counted)} of its "
        f"{len(alert)} extra measures (V1 to V7).",
        "",
        "Read a row as: test, the clause of the measure it answers, the strength of the link, and the scope the "
        "verdict holds for. *Direct*: the setting or state read is what the clause asks for. *Partial*: evidence "
        "for part of the clause (a policy without the outcome, or the author's reading). *Indicator*: shown in the "
        "report but not counted here as coverage. See [mapping.md](mapping.md).",
        "",
        "**A measure with a test is not a measure that is covered.** NSM's measures span clients, servers, network "
        "equipment and processes; a test answers one clause within one scope. A measure without a test is not "
        "measured by this pack: most are about governance, processes, networks or on-premises systems that a "
        "Microsoft 365 tenant cannot show. Assess them some other way.",
        "",
    ]
    principle = None
    for r in sorted(gp.values(), key=lambda r: [int(p) for p in r["Id"].split(".")]):
        if r["Principle"] != principle:
            principle = r["Principle"]
            lines += ["", f"## {principle}", "", "| Measure | Priority | In alert | Tests: clause, strength, scope |", "| --- | --- | --- | --- |"]
        lines.append(f"| [{r['Id']}]({r['Url']}) | {r['Priority']} | {'yes' if r['InAlert'] else ''} | {cell('nsm-gp-ikt:' + r['Id'])} |")
    lines += ["", "## Alert measures without a GP-IKT number", "", "| Measure | Tests: clause, strength, scope |", "| --- | --- |"]
    for i in alert:
        lines.append(f"| {i} | {cell('nsm-varsel-2026:' + i)} |")
    (ROOT / "docs" / "coverage.md").write_text("\n".join(lines) + "\n")


def main():
    frameworks = {}
    for f in (TESTS / "frameworks").glob("*.json"):
        fw = json.loads(f.read_text())
        frameworks[fw["Framework"]] = {r["Id"]: r for r in fw["Requirements"]}

    mapping = json.loads(MAPPING.read_text())
    rows, sections, cites, maprows = [], [], {}, []
    for ps1 in sorted(TESTS.glob("Test.*.ps1")):
        text, md = ps1.read_text(), ps1.with_suffix(".md").read_text()
        tid, title, severity = (attribute(text, k)[0] for k in ("Id", "Title", "Severity"))
        num = tid.removeprefix("MP.NSM.")
        control = attribute(text, "Control")
        entry = mapping["tests"].get(num)
        assert entry, f"{tid} is not in {MAPPING.name}"
        expected = [c["ref"] for c in entry["cites"] if c["strength"] != "indikator"]
        assert control == expected, f"{tid}: Control {control} differs from the mapping catalogue {expected}"
        for c in entry["cites"]:
            assert c["strength"] in mapping["strengths"], f"{tid}: unknown strength {c['strength']}"
            key, rid = c["ref"].split(":", 1)
            assert rid in frameworks.get(key, {}), f"{tid}: {c['ref']} is not a requirement in the framework files"
            cites.setdefault(c["ref"], []).append((num, c["clause"], c["strength"], entry["scope"]))
        licence = attribute(text, "License")
        permission = [p.removeprefix("Graph:Scope:") for p in attribute(text, "Permission")]
        domain = next((DOMAIN[t] for t in attribute(text, "Tag") if t in DOMAIN), "")

        def link(c):
            key, rid = c["ref"].split(":", 1)
            r = frameworks[key][rid]
            return f"[{rid}{' ' + c['clause'] + ')' if c['clause'] else ''}]({r['Url']}) ({STRENGTH[c['strength']]})"

        nsm = ", ".join(c["ref"].split(":", 1)[1] for c in entry["cites"] if c["strength"] != "indikator") or "– (indicator)"
        rows.append(f"| {tid} | {title} | {nsm} | {domain} | {severity} |")
        ms = ", ".join(entry["mcsb"]) or "–"
        for c in entry["cites"]:
            maprows.append(f"| {num} | {c['ref'].split(':', 1)[1]}{' ' + c['clause'] + ')' if c['clause'] else ''} | {STRENGTH[c['strength']]} | {entry['scope']} | {entry['feature']} | {entry['zeroTrust']} | {ms} |")
        lv = "\n".join(f"- **{name}:** {rule}" for name, rule in levels(md)) or "- See the test's documentation."
        why = "\n".join(f"- {c['ref'].split(':', 1)[1]}: {c['why']}" for c in entry["cites"])
        sections.append(
            f"## {tid}: {title}\n\n"
            f"- **NSM:** {', '.join(link(c) for c in entry['cites'])}\n"
            f"- **Scope:** {entry['scope']}\n"
            f"- **Microsoft feature:** {entry['feature']}. Zero Trust pillar: {entry['zeroTrust']}. Nearest MCSB control: {ms}.\n"
            f"- **Domain:** {domain}. **Severity:** {severity}.\n"
            f"- **Licence:** {', '.join(licence) or 'none declared'}\n"
            f"- **Graph permissions:** {', '.join(f'`{p}`' for p in permission) or 'none declared'}\n\n"
            f"Why this link (as shown in the report):\n\n{why}\n\n"
            f"Levels (only høy grad passes):\n\n{lv}\n"
        )
    extra = set(mapping["tests"]) - {r.split(" | ")[0].removeprefix("| MP.NSM.") for r in rows}
    assert not extra, f"{MAPPING.name} names tests that do not exist: {sorted(extra)}"

    # The pack README is English (docs/language.md); the titles stay Norwegian, as the report shows them.
    table_readme = ("| Test | Title (Norwegian, as in the report) | NSM | Domain | Severity |\n| --- | --- | --- | --- | --- |\n"
                    + "\n".join(rows) + "\n")
    table = "| Test | Title | NSM | Domain | Severity |\n| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n"
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "# Test reference\n\n"
        "Generated by `tools/generate_docs.py` from the tests and the mapping catalogue. Do not edit by hand.\n\n"
        "Titles, levels and the reasons for each link are in Norwegian, as in the Maester report. NSM measure numbers link to NSM's own text.\n\n"
        + table + "\n" + "\n".join(sections)
    )
    write_coverage(frameworks, cites)
    maptable = ("| Test | NSM clause | Strength | Scope | Microsoft feature | Zero Trust pillar | MCSB |\n| --- | --- | --- | --- | --- | --- | --- |\n"
                + "\n".join(maprows) + "\n")
    mapdoc = MAPDOC.read_text()
    assert MSTART in mapdoc and MEND in mapdoc, f"{MAPDOC.name} lacks the mapping markers"
    MAPDOC.write_text(re.sub(re.escape(MSTART) + r".*?" + re.escape(MEND), lambda _: f"{MSTART}\n{maptable}{MEND}", mapdoc, flags=re.S))
    readme = README.read_text()
    readme = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: f"{START}\n{table_readme}{END}", readme, flags=re.S)
    README.write_text(readme)
    print(f"{OUT}: {len(rows)} tests")


if __name__ == "__main__":
    main()
